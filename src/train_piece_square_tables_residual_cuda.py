#!/usr/bin/env python3
"""
Train residual piece-square tables for Anteater Chess.

This script assumes the CSV was generated AFTER the legal-move/orientation fixes.
It trains tables as a correction to the existing eval_total, instead of trying to
replace the evaluator.

Model:
    logit = (eval_total + PST_bias + sum(piece-square residuals)) / temperature

The exported generated_piece_square_tables.h keeps the same symbol names your C
code already uses: PST_PAWN, PST_ROOK, ..., PST_ANTEATER.
"""

import argparse
import csv
import math
import os
import random
from collections import Counter, defaultdict

import numpy as np

try:
    import torch
except ImportError as exc:
    raise SystemExit("PyTorch is required. Install a CUDA-enabled torch build if you want --device cuda.") from exc

PIECE_ORDER = ["PAWN", "ROOK", "KING", "QUEEN", "KNIGHT", "BISHOP", "ANTEATER"]
PIECE_TO_INDEX = {name: i for i, name in enumerate(PIECE_ORDER)}
CHAR_TO_PIECE = {
    "P": "PAWN", "p": "PAWN",
    "R": "ROOK", "r": "ROOK",
    "K": "KING", "k": "KING",
    "Q": "QUEEN", "q": "QUEEN",
    "N": "KNIGHT", "n": "KNIGHT",
    "B": "BISHOP", "b": "BISHOP",
    "A": "ANTEATER", "a": "ANTEATER",
}
ROWS = 8
COLS = 10
FEATURES = len(PIECE_ORDER) * ROWS * COLS


def color_of_char(ch: str) -> str:
    return "WHITE" if ch.isupper() else "BLACK"


def feature_index(piece_name: str, row: int, col: int) -> int:
    return (PIECE_TO_INDEX[piece_name] * ROWS * COLS) + (row * COLS) + col


def parse_board_to_features(board: str, side_to_move: str) -> np.ndarray:
    x = np.zeros(FEATURES, dtype=np.float32)
    ranks = board.strip().split("/")
    if len(ranks) != ROWS:
        raise ValueError(f"board has {len(ranks)} rows, expected {ROWS}: {board}")

    for row, rank in enumerate(ranks):
        if len(rank) != COLS:
            raise ValueError(f"board row has {len(rank)} cols, expected {COLS}: {rank}")

        for col, ch in enumerate(rank):
            if ch == ".":
                continue
            if ch not in CHAR_TO_PIECE:
                raise ValueError(f"unknown piece char {ch!r} in board {board}")

            piece = CHAR_TO_PIECE[ch]
            color = color_of_char(ch)

            # Tables are stored from each piece's own perspective.
            # White uses row directly; Black uses mirrored row.
            table_row = row if color == "WHITE" else (ROWS - 1 - row)

            sign = 1.0 if color == side_to_move else -1.0
            x[feature_index(piece, table_row, col)] += sign

    return x


def load_csv(path: str, max_rows: int | None = None, seed: int = 1):
    xs = []
    base_scores = []
    ys = []
    side_counts = Counter()
    result_counts = Counter()
    skipped = 0
    bad = 0

    with open(path, newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            try:
                result = int(row["final_result_for_side"])
                if result == 0:
                    skipped += 1
                    continue

                side = row["side_to_move"]
                if side not in ("WHITE", "BLACK"):
                    skipped += 1
                    continue

                board = row["board"]
                base = float(row.get("eval_total", row.get("search_score", 0)))

                x = parse_board_to_features(board, side)

                xs.append(x)
                base_scores.append(base)
                ys.append(1.0 if result > 0 else 0.0)
                side_counts[side] += 1
                result_counts["side_to_move_won" if result > 0 else "side_to_move_lost"] += 1

                if max_rows is not None and len(xs) >= max_rows:
                    break
            except Exception:
                bad += 1
                continue

    if not xs:
        raise SystemExit("No labeled rows loaded. Check CSV and final_result_for_side column.")

    X = np.stack(xs).astype(np.float32)
    base = np.asarray(base_scores, dtype=np.float32)
    y = np.asarray(ys, dtype=np.float32)

    return X, base, y, skipped, bad, side_counts, result_counts


def accuracy_from_logits(logits: torch.Tensor, y: torch.Tensor) -> float:
    pred = (logits >= 0).float()
    return (pred == y).float().mean().item()


def export_header(path: str, weights: np.ndarray, bias: float, clamp: int):
    table = weights.reshape(len(PIECE_ORDER), ROWS, COLS)
    table = np.rint(table).astype(np.int32)
    if clamp > 0:
        table = np.clip(table, -clamp, clamp)
        bias_int = int(np.clip(round(bias), -clamp, clamp))
    else:
        bias_int = int(round(bias))

    with open(path, "w") as out:
        out.write("#ifndef GENERATED_PIECE_SQUARE_TABLES_H\n")
        out.write("#define GENERATED_PIECE_SQUARE_TABLES_H\n\n")
        out.write("/* Generated by train_piece_square_tables_residual_cuda.py.\n")
        out.write("   These are residual centipawn corrections, not full piece values.\n")
        out.write("   For BLACK pieces, mirror row in C before lookup. */\n\n")
        out.write("#define PST_ROWS 8\n")
        out.write("#define PST_COLS 10\n")
        out.write(f"#define PST_BIAS {bias_int}\n\n")

        for pi, name in enumerate(PIECE_ORDER):
            out.write(f"static const int PST_{name}[PST_ROWS][PST_COLS] = {{\n")
            for r in range(ROWS):
                vals = ", ".join(f"{int(table[pi, r, c]):5d}" for c in range(COLS))
                comma = "," if r != ROWS - 1 else ""
                out.write(f"    {{ {vals} }}{comma}\n")
            out.write("};\n\n")

        out.write("#endif\n")

    print(f"Wrote: {path}")
    print("Residual PST table summary after export clamp:")
    for pi, name in enumerate(PIECE_ORDER):
        vals = table[pi]
        print(f"  {name:9s}: min={vals.min():5d}, max={vals.max():5d}, mean={vals.mean():7.2f}")
    print(f"  PST_BIAS : {bias_int}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("csv_path")
    parser.add_argument("output_header")
    parser.add_argument("--device", default="cuda", choices=["cuda", "cpu"])
    parser.add_argument("--epochs", type=int, default=1200)
    parser.add_argument("--lr", type=float, default=0.08)
    parser.add_argument("--temperature", type=float, default=400.0,
                        help="Centipawn scale for logistic conversion. Larger = softer.")
    parser.add_argument("--l2", type=float, default=2e-4,
                        help="L2 regularization on PST weights.")
    parser.add_argument("--clamp", type=int, default=120,
                        help="Clamp exported residual table values to +/- this. 0 disables clamp.")
    parser.add_argument("--test-split", type=float, default=0.2)
    parser.add_argument("--max-rows", type=int, default=None)
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()

    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)

    X, base, y, skipped, bad, side_counts, result_counts = load_csv(
        args.csv_path, args.max_rows, args.seed
    )

    n = len(y)
    print(f"Loaded labeled samples: {n}")
    print(f"Skipped draw/unknown samples: {skipped}")
    print(f"Bad rows skipped: {bad}")
    print(f"Side counts: {dict(side_counts)}")
    print(f"Result counts: {dict(result_counts)}")

    base_pred = (base >= 0).astype(np.float32)
    base_acc = (base_pred == y).mean()
    print(f"Base eval_total sign accuracy: {base_acc * 100:.2f}%")

    device = args.device
    if device == "cuda" and not torch.cuda.is_available():
        print("CUDA requested but unavailable; using CPU.")
        device = "cpu"
    print(f"Device: {device}")
    if device == "cuda":
        print(f"CUDA device name: {torch.cuda.get_device_name(0)}")

    idx = np.arange(n)
    np.random.shuffle(idx)
    test_n = max(1, int(n * args.test_split))
    test_idx = idx[:test_n]
    train_idx = idx[test_n:]

    X_train = torch.tensor(X[train_idx], device=device)
    b_train = torch.tensor(base[train_idx], device=device)
    y_train = torch.tensor(y[train_idx], device=device)

    X_test = torch.tensor(X[test_idx], device=device)
    b_test = torch.tensor(base[test_idx], device=device)
    y_test = torch.tensor(y[test_idx], device=device)

    w = torch.zeros(FEATURES, device=device, requires_grad=True)
    bias = torch.zeros((), device=device, requires_grad=True)

    opt = torch.optim.AdamW([w, bias], lr=args.lr, weight_decay=0.0)
    bce = torch.nn.BCEWithLogitsLoss()

    def logits_for(Xt, bt):
        correction = Xt.matmul(w) + bias
        return (bt + correction) / args.temperature

    with torch.no_grad():
        base_train_acc = accuracy_from_logits(b_train / args.temperature, y_train)
        base_test_acc = accuracy_from_logits(b_test / args.temperature, y_test)
        print(f"Base-only split accuracy: train={base_train_acc*100:.2f}%, test={base_test_acc*100:.2f}%")

    report_every = max(1, args.epochs // 4)
    for epoch in range(1, args.epochs + 1):
        opt.zero_grad(set_to_none=True)
        logits = logits_for(X_train, b_train)
        loss = bce(logits, y_train) + args.l2 * torch.mean(w * w)
        loss.backward()
        opt.step()

        if epoch == 1 or epoch % report_every == 0 or epoch == args.epochs:
            with torch.no_grad():
                train_acc = accuracy_from_logits(logits_for(X_train, b_train), y_train)
                test_acc = accuracy_from_logits(logits_for(X_test, b_test), y_test)
                avg_abs = torch.mean(torch.abs(X_train.matmul(w) + bias)).item()
                print(
                    f"epoch {epoch:5d}/{args.epochs}: "
                    f"loss={loss.item():.6f}, "
                    f"train_acc={train_acc*100:.2f}%, "
                    f"test_acc={test_acc*100:.2f}%, "
                    f"avg_abs_pst_correction={avg_abs:.1f}"
                )

    with torch.no_grad():
        final_train_acc = accuracy_from_logits(logits_for(X_train, b_train), y_train)
        final_test_acc = accuracy_from_logits(logits_for(X_test, b_test), y_test)
        avg_abs = torch.mean(torch.abs(X_train.matmul(w) + bias)).item()
        weights_np = w.detach().cpu().numpy()
        bias_float = float(bias.detach().cpu().item())

    print("Final accuracy:")
    print(f"  Base train accuracy:         {base_train_acc*100:.2f}%")
    print(f"  Base test accuracy:          {base_test_acc*100:.2f}%")
    print(f"  Residual PST train accuracy: {final_train_acc*100:.2f}%")
    print(f"  Residual PST test accuracy:  {final_test_acc*100:.2f}%")
    print(f"  Avg abs PST correction:      {avg_abs:.2f}")

    export_header(args.output_header, weights_np, bias_float, args.clamp)


if __name__ == "__main__":
    main()
